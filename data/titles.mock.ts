function slugToTitle(slug: string) {
  return slug
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

// Shared hash used anywhere the app needs a stable pseudo-random value
// derived from a slug (fallback title generation, related-titles shuffle)
// — one implementation instead of two copies that happened to do the
// same thing.
export function hashSlug(slug: string): number {
  let hash = 0;
  for (let i = 0; i < slug.length; i++) {
    hash = (hash * 31 + slug.charCodeAt(i)) >>> 0;
  }
  return hash;
}

export function getTitleBySlug(slug: string): Title | undefined {
  return titles.find((t) => t.slug === slug);
}

// Every slug in the app resolves to something here, even ones outside the
// curated list above — we haven't confirmed what metadata DramaBoss will
// actually provide yet, so an uncurated slug falls back to a generic (but
// plausible) placeholder rather than a broken page.
export function getTitleBySlugOrFallback(slug: string): Title {
  const found = getTitleBySlug(slug);
  if (found) return found;

  const hash = hashSlug(slug);
  return {
    id: `fallback-${slug}`,
    slug,
    title: slugToTitle(slug),
    poster: FALLBACK_POSTERS[hash % FALLBACK_POSTERS.length],
    synopsis:
      "Full synopsis for this title hasn't synced from the catalog yet. Once channel metadata is confirmed, this placeholder will be replaced with the real synopsis, tags, and episode details.",
    channel: "DramaShort Originals",
    genre: "Romance",
    tags: ["Romance", "Drama"],
    totalEpisodes: 20 + (hash % 25),
    rating: undefined,
    views: 10000 + (hash % 40000),
    createdAt: "2026-08-01",
    status: "Published",
    year: 2026,
  };
}
